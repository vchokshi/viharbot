"""Backend-agnostic repository interface for governed memory.

The service layer decides *whether* a caller may act (policy, classification ceiling, limits). A
repository decides what the stored state allows (lifecycle, rev, expiry, idempotency, tombstones)
and applies it atomically. Every mutation takes a ``guard`` that the repository calls after it has
locked the record and before it writes, so an authorization that changed since the service looked
refuses the write instead of racing it.

Content never appears in an exception, a log line or an idempotency result.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import datetime
from typing import Callable, Sequence


# --- errors -----------------------------------------------------------------------------------


class MemoryStoreError(Exception):
    """Base class. ``code`` is a fixed string that is safe to return and to log."""

    code = "error"

    def __init__(self, code: str | None = None) -> None:
        super().__init__(code or self.code)
        if code:
            self.code = code


class NotFoundError(MemoryStoreError):
    """Missing, erased, expired, outside the caller's scope or above its classification ceiling."""

    code = "not_found"


class ConflictError(MemoryStoreError):
    """rev mismatch, retired record, or an idempotency key reused for a different request."""

    code = "conflict"


class RefusedError(MemoryStoreError):
    """A rule on the stored state refuses the change (for example lowering a classification)."""

    code = "refused"


class GuardRefusedError(MemoryStoreError):
    """The authorization guard failed inside the transaction (policy changed after the check)."""

    code = "guard_refused"


class TombstonedError(MemoryStoreError):
    """The id or idempotency key belongs to an erased record and may never be used again."""

    code = "tombstoned"


class StorageUnavailableError(MemoryStoreError):
    """The backend failed or timed out. Retryable; carries no detail."""

    code = "storage_unavailable"


# --- value objects ----------------------------------------------------------------------------


@dataclass(frozen=True)
class Scope:
    tier: str  # "agent" or "session"
    key: str  # the agent id or the session id

    @property
    def memory_type(self) -> str:
        return "agent_private" if self.tier == "agent" else "session"


@dataclass(frozen=True)
class Provenance:
    kind: str
    source_id: str
    author: str  # derived from the verified caller, never from the request
    request_id: str | None


@dataclass(frozen=True)
class NewRecord:
    memory_id: str  # generated by the service, never by the caller
    content: str
    provenance: Provenance
    classification: str
    tags: tuple[str, ...]
    personal_data: bool
    consent_basis: str
    consent_reference: str | None
    retention_until: datetime | None
    expires_at: datetime | None


@dataclass(frozen=True)
class NewVersion:
    content: str
    provenance: Provenance
    tags: tuple[str, ...] | None  # None keeps the current tags
    classification: str | None  # None keeps the current class; a lower class is refused


@dataclass(frozen=True)
class Record:
    memory_id: str
    memory_type: str
    scope_key: str
    owner_agent_id: str
    content: str
    provenance: Provenance
    classification: str
    tags: tuple[str, ...]
    personal_data: bool
    consent_basis: str
    consent_reference: str | None
    retention_until: datetime | None
    expires_at: datetime | None
    created_at: datetime
    updated_at: datetime
    version: int
    rev: int
    lifecycle: str


@dataclass(frozen=True)
class WriteContext:
    """Everything a mutation needs besides its payload. All of it is derived, none of it asserted."""

    principal: str  # the verified sub
    owner: str  # the derived agent id
    scope: Scope
    request_id: str
    now: datetime  # supplied by the service clock, never by the database
    guard: Callable[[], bool]  # re-checks authorization inside the transaction
    allowed_classes: Sequence[str] | None  # classes the caller may touch; None means any
    idempotency_key: str | None = None
    request_hash: str = ""


@dataclass(frozen=True)
class MutationResult:
    status: int
    body: dict = field(default_factory=dict)  # metadata only, never content
    replayed: bool = False


# --- interface --------------------------------------------------------------------------------


class MemoryRepository(ABC):
    """What the memory service needs from a store. PostgreSQL is the only implementation."""

    @abstractmethod
    def ping(self) -> None:
        """Raise StorageUnavailableError if the primary cannot be reached."""

    @abstractmethod
    def get(
        self, scope: Scope, owner: str, memory_id: str, now: datetime, allowed_classes: Sequence[str]
    ) -> Record | None:
        """An active, unexpired record in exactly this owner and scope, else None."""

    @abstractmethod
    def list(
        self, scope: Scope, owner: str, now: datetime, allowed_classes: Sequence[str],
        tag: str | None, limit: int,
    ) -> list[Record]:
        """Active, unexpired records in exactly this owner and scope, newest first."""

    @abstractmethod
    def create(self, new: NewRecord, ctx: WriteContext) -> MutationResult:
        """Create a record at rev 1 and version 1. Refuses a tombstoned id or key."""

    @abstractmethod
    def update(self, memory_id: str, expected_rev: int, change: NewVersion, ctx: WriteContext) -> MutationResult:
        """Publish a new content version. Fails unless rev matches and the record is active."""

    @abstractmethod
    def classify(self, memory_id: str, expected_rev: int, classification: str, ctx: WriteContext) -> MutationResult:
        """Raise the classification. Advances rev, not version. Allowed on a retired record."""

    @abstractmethod
    def retire(self, memory_id: str, ctx: WriteContext) -> MutationResult:
        """Stop normal serving. History is kept. Idempotent."""

    @abstractmethod
    def erase(self, memory_id: str, reason: str, ctx: WriteContext) -> MutationResult:
        """Stage one: logical erasure (the write barrier) takes effect at once. Idempotent."""

    @abstractmethod
    def complete_erasure(self, memory_id: str, now: datetime) -> bool:
        """Stage two: physically delete the rows and write the tombstone. True if completed."""

    @abstractmethod
    def pending_erasures(self) -> list[str]:
        """Memory ids whose erase barrier committed but whose physical deletion has not."""
