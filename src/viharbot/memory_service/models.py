"""Request bodies for the memory API.

Every body forbids extra fields. In particular a body can never name an agent, an owner, a scope,
an engagement, a memory id on create, a version, a lifecycle or an author: those are derived from
the verified token and the path, or generated by the service, and a request that supplies them is
refused whole. Validation errors are never echoed back (they could carry content).
"""

from __future__ import annotations

from datetime import datetime
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field, StringConstraints, field_validator

from ..knowledge.models import SourceKind

IdempotencyKey = Annotated[str, StringConstraints(pattern=r"^[A-Za-z0-9._:-]{8,128}$")]
Tag = Annotated[str, StringConstraints(pattern=r"^[a-z0-9][a-z0-9._-]{0,31}$")]
SourceId = Annotated[str, StringConstraints(pattern=r"^[!-~][ -~]{0,255}$")]
ConsentReference = Annotated[str, StringConstraints(pattern=r"^[!-~][ -~]{0,127}$")]
Classification = Literal["public", "internal", "confidential", "restricted"]
EraseReason = Literal["consent_withdrawn", "owner_request", "policy", "other"]
MAX_TAGS = 8
MAX_TTL_SECONDS = 30 * 86400


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)


class ProvenanceIn(_Strict):
    """What the content came from. The author is not here: it is the caller's derived agent id."""

    kind: SourceKind
    source_id: SourceId


class Consent(_Strict):
    basis: Literal["not_applicable", "consent_recorded"] = "not_applicable"
    reference: ConsentReference | None = None


def _checked_text(value: str) -> str:
    if "\x00" in value:
        raise ValueError("NUL is not allowed")
    value.encode("utf-8")  # a lone surrogate cannot be stored
    if not value.strip():
        raise ValueError("content is empty")
    return value


def _unique(tags: list[str] | None) -> list[str] | None:
    if tags is not None and len(set(tags)) != len(tags):
        raise ValueError("duplicate tags")
    return tags


class CreateRequest(_Strict):
    idempotency_key: IdempotencyKey
    content: str
    provenance: ProvenanceIn
    classification: Classification = "internal"
    tags: list[Tag] = Field(default_factory=list, max_length=MAX_TAGS)
    retention_until: datetime | None = None  # agent-private records only
    ttl_seconds: int | None = Field(default=None, ge=1, le=MAX_TTL_SECONDS)  # session records only
    personal_data: bool = False
    consent: Consent = Field(default_factory=Consent)

    _content = field_validator("content")(_checked_text)
    _tags = field_validator("tags")(_unique)


class UpdateRequest(_Strict):
    idempotency_key: IdempotencyKey
    expected_rev: int = Field(ge=1)
    content: str
    provenance: ProvenanceIn
    tags: list[Tag] | None = Field(default=None, max_length=MAX_TAGS)
    classification: Classification | None = None  # may be raised, never lowered

    _content = field_validator("content")(_checked_text)
    _tags = field_validator("tags")(_unique)


class ClassifyRequest(_Strict):
    idempotency_key: IdempotencyKey
    expected_rev: int = Field(ge=1)
    classification: Classification


class RetireRequest(_Strict):
    pass


class EraseRequest(_Strict):
    reason: EraseReason


BODY_MODELS: dict[str, type[_Strict]] = {
    "create": CreateRequest,
    "update": UpdateRequest,
    "classify": ClassifyRequest,
    "retire": RetireRequest,
    "erase": EraseRequest,
}
