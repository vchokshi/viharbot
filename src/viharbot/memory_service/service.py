"""Memory service rules: who may do what, what a record may hold, and how it is returned.

The caller's agent identity comes from the policy table entry for the verified ``sub`` and from
nothing else. The scope comes from the path. Content, classification, retention and the rest come
from the request but are bounded by that agent's policy. The repository then applies what the
stored state allows. Retrieval returns content wrapped as data, with provenance and a
not-instructions marker, and only from the caller's own scope.
"""

